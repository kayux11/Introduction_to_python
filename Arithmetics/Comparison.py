# Equal to
is_equal = (5 == 5)  # is_equal will be True

# Not equal to
is_not_equal = (5 != 10)  # is_not_equal will be True

# Greater than
is_greater = (10 > 5)  # is_greater will be True

# Less than
is_less = (5 < 10)  # is_less will be True

# Greater than or equal to
is_greater_equal = (10 >= 10)  # is_greater_equal will be True

# Less than or equal to
is_less_equal = (5 <= 10)  # is_less_equal will be True