# Addition
result_add = 10 + 5  # result_add will be 15

# Subtraction
result_sub = 10 - 5  # result_sub will be 5

# Multiplication
result_mul = 10 * 5  # result_mul will be 50

# Division (float division)
result_div = 10 / 3  # result_div will be 3.333...

# Floor Division (integer division, rounds down)
result_floor_div = 10 // 3  # result_floor_div will be 3

# Modulo (remainder of division)
result_mod = 10 % 3  # result_mod will be 1

# Exponentiation (power)
result_exp = 2 ** 3  # result_exp will be 8 (2 to the power of 3)


# more practices
a = 5
b = 2
a//b == 5//2 # the result is 2
a % b == 5 % 2 # the result is 1
a **b == 5**2 # the result is 25